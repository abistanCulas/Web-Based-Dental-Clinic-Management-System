package com.dentaflow.backend.repository;

import com.dentaflow.backend.entity.Report;
import org.springframework.data.jpa.repository.JpaRepository;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Optional;

public interface ReportRepository
        extends JpaRepository<Report, Long> {

    // Find report by unique report code
    Optional<Report> findByReportCode(
            String reportCode
    );

    // Check report code
    boolean existsByReportCode(
            String reportCode
    );

    // Find reports by type
    List<Report> findByReportTypeIgnoreCaseOrderByGeneratedAtDesc(
            String reportType
    );

    // Find reports by status
    List<Report> findByStatusIgnoreCaseOrderByGeneratedAtDesc(
            String status
    );

    // Find reports generated by a user/staff
    List<Report> findByGeneratedByContainingIgnoreCaseOrderByGeneratedAtDesc(
            String generatedBy
    );

    // Find reports between two dates
    List<Report> findByGeneratedAtBetweenOrderByGeneratedAtDesc(
            LocalDateTime startDate,
            LocalDateTime endDate
    );

    // Search reports by title
    List<Report> findByTitleContainingIgnoreCaseOrderByGeneratedAtDesc(
            String title
    );

    // Find reports by type and status
    List<Report> findByReportTypeIgnoreCaseAndStatusIgnoreCaseOrderByGeneratedAtDesc(
            String reportType,
            String status
    );
}
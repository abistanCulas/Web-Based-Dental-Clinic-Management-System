import { useEffect, useState } from 'react'
import { Plus, FileBarChart, Trash2 } from 'lucide-react'
import { BarChart, Bar, XAxis, YAxis, Tooltip, ResponsiveContainer, CartesianGrid } from 'recharts'
import { ReportApi, extractErrorMessage } from '../api/client.js'
import EmptyState from '../components/EmptyState.jsx'
import Drawer from '../components/Drawer.jsx'

const REPORT_TYPES = [
  { value: 'FEEDBACK_SUMMARY', label: 'Feedback summary' },
  { value: 'INQUIRY_SUMMARY', label: 'Inquiry summary' },
  { value: 'REVENUE_REPORT', label: 'Revenue report' },
  { value: 'APPOINTMENT_REPORT', label: 'Appointment report' },
]

const TYPE_LABEL = Object.fromEntries(REPORT_TYPES.map(t => [t.value, t.label]))

function formatDate(value) {
  if (!value) return '—'
  return new Date(value).toLocaleString(undefined, {
    year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit',
  })
}

export default function ReportsPage() {
  const [reports, setReports] = useState([])
  const [loading, setLoading] = useState(true)
  const [listError, setListError] = useState('')
  const [showCreate, setShowCreate] = useState(false)
  const [selected, setSelected] = useState(null)

  function load() {
    setLoading(true)
    ReportApi.list()
      .then(setReports)
      .catch((err) => setListError(extractErrorMessage(err)))
      .finally(() => setLoading(false))
  }

  useEffect(load, [])

  async function handleDelete(id) {
    if (!confirm('Delete this report? This cannot be undone.')) return
    await ReportApi.remove(id)
    load()
  }

  const sorted = [...reports].sort((a, b) => new Date(b.generatedDate) - new Date(a.generatedDate))

  return (
    <>
      <header className="page-header">
        <div>
          <h1 className="page-title">Reports</h1>
          <p className="page-subtitle">
            Generate clinic reports for a date range and keep a history of past runs.
          </p>
        </div>
        <button className="btn btn-primary" onClick={() => setShowCreate(true)}>
          <Plus size={16} /> Generate report
        </button>
      </header>

      <div className="page-body">
        <div className="panel">
          <div className="panel-header">
            <h2>Report history</h2>
          </div>

          {listError && <div className="alert alert-error" style={{ margin: '16px 20px 0' }}>{listError}</div>}

          {!loading && sorted.length === 0 ? (
            <EmptyState
              icon={FileBarChart}
              title="No reports generated yet"
              description="Choose a report type and date range to generate your first report."
            />
          ) : (
            <table>
              <thead>
                <tr>
                  <th>Type</th>
                  <th>Date range</th>
                  <th>Generated by</th>
                  <th>Generated</th>
                  <th>Records</th>
                  <th></th>
                </tr>
              </thead>
              <tbody>
                {sorted.map(r => (
                  <tr key={r.id}>
                    <td onClick={() => setSelected(r)} style={{ cursor: 'pointer' }} className="cell-primary">
                      {TYPE_LABEL[r.reportType] || r.reportType}
                    </td>
                    <td onClick={() => setSelected(r)} style={{ cursor: 'pointer' }} className="cell-mono">
                      {r.startDate} → {r.endDate}
                    </td>
                    <td onClick={() => setSelected(r)} style={{ cursor: 'pointer' }}>{r.generatedBy}</td>
                    <td onClick={() => setSelected(r)} style={{ cursor: 'pointer' }} className="cell-mono">
                      {formatDate(r.generatedDate)}
                    </td>
                    <td onClick={() => setSelected(r)} style={{ cursor: 'pointer' }}>{r.totalRecords}</td>
                    <td>
                      <div className="row-actions">
                        <button className="btn btn-ghost btn-sm" onClick={() => setSelected(r)}>View</button>
                        <button className="btn btn-ghost btn-sm" onClick={() => handleDelete(r.id)} aria-label="Delete">
                          <Trash2 size={15} />
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </div>
      </div>

      {showCreate && (
        <GenerateReportDrawer
          onClose={() => setShowCreate(false)}
          onCreated={(report) => { setShowCreate(false); load(); setSelected(report) }}
        />
      )}

      {selected && (
        <ReportDetailDrawer report={selected} onClose={() => setSelected(null)} />
      )}
    </>
  )
}

function GenerateReportDrawer({ onClose, onCreated }) {
  const today = new Date().toISOString().slice(0, 10)
  const [form, setForm] = useState({
    reportType: 'FEEDBACK_SUMMARY',
    startDate: today,
    endDate: today,
    generatedBy: '',
  })
  const [error, setError] = useState('')
  const [saving, setSaving] = useState(false)

  function update(field, value) { setForm(f => ({ ...f, [field]: value })) }

  async function handleGenerate() {
    setError('')
    setSaving(true)
    try {
      const report = await ReportApi.generate(form)
      onCreated(report)
    } catch (err) {
      // Surfaces extension 5a: invalid date range or missing report criteria.
      setError(extractErrorMessage(err))
    } finally {
      setSaving(false)
    }
  }

  return (
    <Drawer
      title="Generate a report"
      onClose={onClose}
      footer={(
        <>
          <button className="btn btn-outline" onClick={onClose}>Cancel</button>
          <button className="btn btn-primary" onClick={handleGenerate} disabled={saving}>
            {saving ? 'Generating…' : 'Generate report'}
          </button>
        </>
      )}
    >
      {error && <div className="alert alert-error">{error}</div>}

      <div className="field">
        <label>Report type</label>
        <select className="select" value={form.reportType} onChange={e => update('reportType', e.target.value)}>
          {REPORT_TYPES.map(t => <option key={t.value} value={t.value}>{t.label}</option>)}
        </select>
      </div>
      <div className="form-grid">
        <div className="field">
          <label>Start date</label>
          <input className="input" type="date" value={form.startDate} max={today}
            onChange={e => update('startDate', e.target.value)} />
        </div>
        <div className="field">
          <label>End date</label>
          <input className="input" type="date" value={form.endDate}
            onChange={e => update('endDate', e.target.value)} />
        </div>
      </div>
      <div className="field">
        <label>Generated by</label>
        <input className="input" value={form.generatedBy}
          onChange={e => update('generatedBy', e.target.value)} placeholder="Your name" />
      </div>
    </Drawer>
  )
}

function ReportDetailDrawer({ report, onClose }) {
  let data = {}
  try { data = JSON.parse(report.dataJson || '{}') } catch { /* ignore malformed payload */ }

  const ratingChart = data.ratingBreakdown
    ? Object.entries(data.ratingBreakdown).map(([rating, count]) => ({ name: `${rating}★`, count }))
    : null

  const statusChart = data.statusBreakdown
    ? Object.entries(data.statusBreakdown).map(([status, count]) => ({ name: status.replace('_', ' '), count }))
    : null

  return (
    <Drawer
      title={TYPE_LABEL[report.reportType] || report.reportType}
      onClose={onClose}
      footer={<button className="btn btn-outline" onClick={onClose}>Close</button>}
    >
      <div className="detail-block">
        <div className="detail-label">Date range</div>
        <div className="detail-value">{report.startDate} → {report.endDate}</div>
      </div>
      <div className="detail-block">
        <div className="detail-label">Generated by</div>
        <div className="detail-value">{report.generatedBy} · {formatDate(report.generatedDate)}</div>
      </div>
      <div className="detail-block">
        <div className="detail-label">Summary</div>
        <div className="detail-value">{report.summary}</div>
      </div>

      {(ratingChart || statusChart) && (
        <div className="detail-block">
          <div className="detail-label">Breakdown</div>
          <div style={{ height: 220, marginTop: 8 }}>
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={ratingChart || statusChart}>
                <CartesianGrid strokeDasharray="3 3" stroke="#DBE4DF" vertical={false} />
                <XAxis dataKey="name" tick={{ fontSize: 12 }} />
                <YAxis allowDecimals={false} tick={{ fontSize: 12 }} />
                <Tooltip />
                <Bar dataKey="count" fill="#0F5E56" radius={[4, 4, 0, 0]} />
              </BarChart>
            </ResponsiveContainer>
          </div>
        </div>
      )}

      {data.note && (
        <div className="alert alert-error" style={{ marginTop: 16 }}>{data.note}</div>
      )}
    </Drawer>
  )
}
